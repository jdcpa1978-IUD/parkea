CREATE TYPE rol_usuario AS ENUM ('ADMINISTRADOR', 'OPERADOR', 'CLIENTE');
CREATE TYPE estado_usuario AS ENUM ('ACTIVO', 'INACTIVO');
CREATE TYPE tipo_vehiculo_enum AS ENUM ('AUTOMOVIL', 'MOTOCICLETA');
CREATE TYPE estado_celda_enum AS ENUM ('DISPONIBLE', 'OCUPADA', 'MANTENIMIENTO');
CREATE TYPE estado_registro_enum AS ENUM ('INGRESO_ACTIVO', 'FINALIZADO');
CREATE TYPE metodo_pago_enum AS ENUM ('EFECTIVO', 'TRANSFERENCIA', 'TARJETA');

CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    telefono VARCHAR(15),
    email VARCHAR(100) UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol rol_usuario NOT NULL,
    estado estado_usuario NOT NULL DEFAULT 'ACTIVO'
);

CREATE TABLE vehiculos (
    id_vehiculo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(6) NOT NULL UNIQUE CHECK (placa ~ '^[A-Z0-9]{1,6}$'),
    tipo_vehiculo tipo_vehiculo_enum NOT NULL,
    marca VARCHAR(30),
    modelo VARCHAR(30),
    color VARCHAR(20),
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT
);

CREATE TABLE celdas (
    id_celda INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_celda VARCHAR(10) NOT NULL UNIQUE,
    tipo_celda tipo_vehiculo_enum NOT NULL,
    estado estado_celda_enum NOT NULL DEFAULT 'DISPONIBLE'
);

CREATE TABLE registros_acceso (
    id_registro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vehiculo INTEGER NOT NULL REFERENCES vehiculos(id_vehiculo) ON DELETE RESTRICT,
    id_celda INTEGER NOT NULL REFERENCES celdas(id_celda) ON DELETE RESTRICT,
    id_operador_ingreso INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    id_operador_salida INTEGER REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    fecha_hora_ingreso TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_hora_salida TIMESTAMPTZ,
    estado_registro estado_registro_enum NOT NULL DEFAULT 'INGRESO_ACTIVO',
    CONSTRAINT ck_registro_estado_salida CHECK (
        (estado_registro = 'INGRESO_ACTIVO' AND fecha_hora_salida IS NULL)
        OR (estado_registro = 'FINALIZADO' AND fecha_hora_salida IS NOT NULL)
    )
);
CREATE UNIQUE INDEX uq_registro_celda_activa
    ON registros_acceso(id_celda) WHERE estado_registro = 'INGRESO_ACTIVO';
CREATE UNIQUE INDEX uq_registro_vehiculo_activo
    ON registros_acceso(id_vehiculo) WHERE estado_registro = 'INGRESO_ACTIVO';

CREATE TABLE pagos_mensualidad (
    id_pago INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    monto NUMERIC(10, 2) NOT NULL CHECK (monto > 0),
    fecha_pago TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_inicio_vencimiento DATE NOT NULL,
    fecha_fin_vencimiento DATE NOT NULL,
    metodo_pago metodo_pago_enum NOT NULL,
    CONSTRAINT ck_pago_rango_fechas CHECK (fecha_fin_vencimiento >= fecha_inicio_vencimiento)
);
CREATE INDEX ix_pagos_usuario_vigencia
    ON pagos_mensualidad(id_usuario, fecha_inicio_vencimiento, fecha_fin_vencimiento);

CREATE TABLE novedades (
    id_novedad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_registro INTEGER NOT NULL REFERENCES registros_acceso(id_registro) ON DELETE RESTRICT,
    id_operador INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
    descripcion TEXT NOT NULL CHECK (length(trim(descripcion)) > 0),
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

